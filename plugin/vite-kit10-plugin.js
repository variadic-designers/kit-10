function zero() {
	return `${heading('Qatto')}
* {
	box-sizing: border-box;

	margin: 0;
	padding: 0;
}
`;
}

function style() {
	return `${heading('Qatto')}
  
.meow {
  background: black;
  color: yellow;
  font-size: 8rem;
  font-weight: 800;
  font-family: sans-serif;
}`;
}

function deleteArtifact(dir, filename) {
	const path = dir + '/' + filename;

	try {
		fs.unlinkSync(path);
		console.log(`${path} was deleted`);
	} catch (err) {
		console.error(`Failed to delete ${path}:`, err);
		throw err;
	}
}

function artifact(dir, filename, style) {
	fs.mkdirSync(dir, { recursive: true });

	fs.writeFileSync(dir + '/' + filename, style);
}

const modules = {};

export default function kit10() {
	return {
		name: 'kit10',

		buildStart() {
			artifact(BUILD, 'zero.scss', zero());
			artifact(BUILD, 'style.scss', style());
		},

		configureServer(server) {
			artifact(LIVE, 'zero.scss', zero());
			artifact(LIVE, 'style.scss', style());

			server.middlewares.use('/__kit10/update', (req, res) => {
				let body = '';
				req.on('data', (c) => (body += c));

				req.on('end', () => {
					try {
						const payload = JSON.parse(body);

						// update in-memory state
						modules[payload.next.module] = payload.next.style;

						if (payload.next.invalidate) {
							deleteArtifact(LIVE, payload.next.module);
						} else {
							artifact(LIVE, payload.next.module, modules[payload.next.module]);
						}

						res.setHeader('Content-Type', 'application/json');
						res.end(JSON.stringify({ status: 'ok' }));
					} catch (err) {
						res.statusCode = 400;
						res.end('Invalid JSON');
					}
				});
			});
		},

		resolveId(id) {},

		load(id) {}
	};
}
