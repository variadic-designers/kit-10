// Generates the machine-derivable parts of PLUGINS.md from their in-code source of truth, so the
// plugin-author docs cannot silently drift from the shipped contract (see
// resources/api-formalization.md, Phase 2). Today it owns the inputType reference table, derived
// from the `InputType` union in src/lib/plugins/types.ts.
//
//   node scripts/generate-plugin-docs.mjs           # rewrite PLUGINS.md in place
//   node scripts/generate-plugin-docs.mjs --check    # exit 1 if PLUGINS.md is stale (CI guard)
//
// The pure functions are exported for the drift-guard test (generate-plugin-docs.test.ts). Adding
// a new generated section = add a parse+render pair and a marker block, same shape as input-types.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as prettier from 'prettier';

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const TYPES_PATH = resolve(REPO_ROOT, 'src/lib/plugins/types.ts');
const PLUGINS_MD_PATH = resolve(REPO_ROOT, 'PLUGINS.md');
const WIRE_SCHEMA_PATH = resolve(REPO_ROOT, 'plugins/charter/generated/wire-schema.json');

export const INPUT_TYPES_BEGIN = '<!-- BEGIN GENERATED: input-types';
export const INPUT_TYPES_END = '<!-- END GENERATED: input-types';
export const WIRE_TYPES_BEGIN = '<!-- BEGIN GENERATED: wire-types';
export const WIRE_TYPES_END = '<!-- END GENERATED: wire-types';

/** @typedef {{ name: string, doc: string }} InputTypeEntry */

// Parse the `export type InputType = | 'x' | 'y' ...;` union out of types.ts. Each member's row
// description is its `// @doc: ...` comment line; freeform explanatory comments above it are
// ignored. Order is preserved from the union.
/**
 * @param {string} typesSource
 * @returns {InputTypeEntry[]}
 */
export function parseInputTypes(typesSource) {
	const match = typesSource.match(/export type InputType =([\s\S]*?);/);
	if (!match)
		throw new Error('generate-plugin-docs: could not find the `InputType` union in types.ts');

	const entries = [];
	let pendingDoc = null;
	for (const rawLine of match[1].split('\n')) {
		const line = rawLine.trim();
		const doc = line.match(/^\/\/\s*@doc:\s*(.+?)\s*$/);
		if (doc) {
			pendingDoc = doc[1];
			continue;
		}
		const member = line.match(/^\|\s*'([^']+)'/);
		if (member) {
			entries.push({ name: member[1], doc: pendingDoc ?? '' });
			pendingDoc = null;
		}
	}
	if (entries.length === 0) throw new Error('generate-plugin-docs: parsed zero InputType members');
	return entries;
}

// The set of host functions actually registered in makeHostFunctions (manager.svelte.ts). Their
// prose docs in PLUGINS.md stay hand-written (rich, per-fn), so this is a NAME-set guard, not a
// generator: the drift test asserts the documented set equals this set, catching a host fn added
// or removed without a PLUGINS.md update. Matches each `kit10_x(` (optionally `async`) method.
/**
 * @param {string} managerSource
 * @returns {string[]}
 */
export function parseRegisteredHostFns(managerSource) {
	const names = new Set();
	for (const m of managerSource.matchAll(/^\s*(?:async\s+)?(kit10_[a-z0-9_]+)\s*\(/gm)) {
		names.add(m[1]);
	}
	return [...names].sort();
}

// The host functions PLUGINS.md documents, read from its `### `kit10_x...`` headings.
/**
 * @param {string} pluginsMd
 * @returns {string[]}
 */
export function parseDocumentedHostFns(pluginsMd) {
	const names = new Set();
	for (const m of pluginsMd.matchAll(/^###\s+`(kit10_[a-z0-9_]+)/gm)) {
		names.add(m[1]);
	}
	return [...names].sort();
}

// The top-level field names of each UiNode variant, read from the wire JSON Schema's node `$defs`
// (BoxData/TextData/ImgData) - the machine-truth source, generated by the kit10-protocol crate.
// Used to guard that PLUGINS.md's node examples document every real field, so the illustrative JSON
// can't silently fall behind the actual wire (the exact drift that let colors-as-arrays and missing
// fields ship before). Returns e.g. { Box: [...], Text: [...], Img: [...] }.
/**
 * @param {string} schemaJson
 * @returns {Record<string, string[]>}
 */
export function nodeFieldsFromSchema(schemaJson) {
	const defs = JSON.parse(schemaJson).$defs || {};
	const byVariant = { Box: 'BoxData', Text: 'TextData', Img: 'ImgData' };
	/** @type {Record<string, string[]>} */
	const out = {};
	for (const [variant, def] of Object.entries(byVariant)) {
		if (!defs[def]) throw new Error(`generate-plugin-docs: wire schema missing $defs.${def}`);
		out[variant] = Object.keys(defs[def].properties || {});
	}
	return out;
}

// Extract the body of the first ```json fenced block after a prose marker (e.g. "**Box node:**").
/**
 * @param {string} md
 * @param {string} marker
 * @returns {string}
 */
export function extractJsonBlockAfter(md, marker) {
	const start = md.indexOf(marker);
	if (start === -1) throw new Error(`generate-plugin-docs: marker "${marker}" not found`);
	const fence = md.indexOf('```json', start);
	if (fence === -1) throw new Error(`generate-plugin-docs: no json block after "${marker}"`);
	const bodyStart = md.indexOf('\n', fence) + 1;
	const end = md.indexOf('```', bodyStart);
	if (end === -1)
		throw new Error(`generate-plugin-docs: unterminated json block after "${marker}"`);
	return md.slice(bodyStart, end);
}

// Render the inputType reference table (GitHub-flavored markdown). A missing @doc is surfaced
// loudly in the cell rather than silently blank, so the drift test catches it.
/**
 * @param {InputTypeEntry[]} entries
 * @returns {string}
 */
export function renderInputTypeTable(entries) {
	const rows = entries.map((e) => `| \`${e.name}\` | ${e.doc || '**(missing @doc)**'} |`);
	return ['| `inputType` | Widget |', '| --- | --- |', ...rows].join('\n');
}

// --- Wire-type reference, rendered from Charter's schemars-derived JSON Schema ------------------
// Source of truth: plugins/charter/generated/wire-schema.json (regenerated by `cargo test
// --features schema`). This renders that machine-truth schema into PLUGINS.md's wire-type tables,
// so the field-by-field contract is DERIVED from the Rust structs, never hand-written. schemars 1.x
// shape: a `$defs` map; structs are { properties, required }; Rust enums are `oneOf` (unit variant
// = {enum:["X"]}, data variant = {properties:{Variant: payload}}); Option<T> is an `anyOf` whose
// branches include {type:"null"}; tuples use `prefixItems`; Vec uses `items`; [T;N] sets min==max.

/** @param {string} ref @returns {string} */
function refName(ref) {
	return ref.split('/').pop() ?? ref;
}

// A compact human type label for one schema node (a field's type, or an enum-variant payload).
/**
 * @param {any} s
 * @returns {string}
 */
export function typeLabel(s) {
	if (!s || typeof s !== 'object') return '-';
	if (s.$ref) return refName(s.$ref);
	if (Array.isArray(s.anyOf)) {
		const nonNull = s.anyOf.filter((/** @type {any} */ x) => !(x && x.type === 'null'));
		const nullable = nonNull.length !== s.anyOf.length;
		return nonNull.map(typeLabel).join(' | ') + (nullable ? '?' : '');
	}
	if (Array.isArray(s.oneOf)) return s.oneOf.map(typeLabel).join(' | ');
	if (Array.isArray(s.type)) {
		const nn = s.type.filter((/** @type {string} */ t) => t !== 'null');
		return nn.join(' | ') + (s.type.includes('null') ? '?' : '');
	}
	if (s.type === 'array') {
		if (Array.isArray(s.prefixItems)) return `[${s.prefixItems.map(typeLabel).join(', ')}]`;
		if (s.items && s.minItems != null && s.minItems === s.maxItems) {
			return `[${typeLabel(s.items)} × ${s.maxItems}]`;
		}
		return `${typeLabel(s.items)}[]`;
	}
	if (Array.isArray(s.enum) && s.type === 'string') {
		return s.enum.map((/** @type {string} */ e) => `"${e}"`).join(' | ');
	}
	if (typeof s.type === 'string') return s.type;
	return '-';
}

// One variant of a Rust enum (a `oneOf` entry), for the bullet list under an enum type.
/**
 * @param {any} v
 * @returns {string}
 */
export function variantLabel(v) {
	if (v.type === 'string' && Array.isArray(v.enum)) {
		return v.enum.map((/** @type {string} */ e) => `"${e}"`).join(', ');
	}
	if (v.type === 'object' && v.properties) {
		const body = Object.entries(v.properties)
			.map(([k, ps]) => `"${k}": ${typeLabel(ps)}`)
			.join(', ');
		return `{ ${body} }`;
	}
	return typeLabel(v);
}

/**
 * @param {string} name
 * @param {any} def
 * @returns {string}
 */
function renderWireType(name, def) {
	const out = [`#### \`${name}\``, ''];
	if (def.properties) {
		const required = new Set(def.required || []);
		out.push('| Field | Type | Required |', '| --- | --- | --- |');
		for (const [field, fs] of Object.entries(def.properties)) {
			const type = typeLabel(fs).replace(/\|/g, '\\|');
			out.push(`| \`${field}\` | ${type} | ${required.has(field) ? '✓' : '-'} |`);
		}
	} else if (Array.isArray(def.oneOf)) {
		out.push('One of:', '');
		for (const v of def.oneOf) out.push(`- \`${variantLabel(v)}\``);
	} else if (Array.isArray(def.enum)) {
		// A pure unit enum (e.g. AlignValue) - schemars emits a bare string enum, not a oneOf.
		out.push('One of: ' + def.enum.map((/** @type {string} */ e) => `\`"${e}"\``).join(', '));
	}
	return out.join('\n');
}

// Render every type in the schema's `$defs` as a markdown section - node bodies first, then the
// leaf value types alphabetically.
/**
 * @param {string} schemaJson
 * @returns {string}
 */
export function renderWireTypes(schemaJson) {
	const defs = JSON.parse(schemaJson).$defs || {};
	const first = ['BoxData', 'TextData', 'ImgData'];
	const rest = Object.keys(defs)
		.filter((n) => !first.includes(n))
		.sort();
	const order = [...first.filter((n) => defs[n]), ...rest];
	if (order.length === 0) throw new Error('generate-plugin-docs: wire schema has no $defs');
	return order.map((n) => renderWireType(n, defs[n])).join('\n\n');
}

// Replace the text between a BEGIN/END marker pair (matched by stable prefix, not exact text, so
// the marker line's trailing prose can change without breaking the anchor). The marker lines
// themselves are preserved; `content` lands between them, blank-line padded.
/**
 * @param {string} source
 * @param {string} beginPrefix
 * @param {string} endPrefix
 * @param {string} content
 * @returns {string}
 */
export function injectBetweenMarkers(source, beginPrefix, endPrefix, content) {
	const lines = source.split('\n');
	const beginIdx = lines.findIndex((l) => l.startsWith(beginPrefix));
	const endIdx = lines.findIndex((l) => l.startsWith(endPrefix));
	if (beginIdx === -1 || endIdx === -1 || endIdx < beginIdx) {
		throw new Error(
			`generate-plugin-docs: markers "${beginPrefix}" / "${endPrefix}" not found (or out of order)`
		);
	}
	const rebuilt = [...lines.slice(0, beginIdx + 1), '', content, '', ...lines.slice(endIdx)];
	return rebuilt.join('\n');
}

// Run a markdown fragment through the repo's Prettier config so the generated table lands
// column-aligned exactly the way `prettier --write` would produce it - otherwise the generator and
// Prettier would fight over the same lines forever. Table alignment depends only on the table's own
// cells, so formatting the standalone snippet matches how Prettier renders it in-file.
/**
 * @param {string} fragment
 * @returns {Promise<string>}
 */
async function formatMarkdown(fragment) {
	const config = (await prettier.resolveConfig(PLUGINS_MD_PATH)) ?? {};
	const out = await prettier.format(fragment, { ...config, parser: 'markdown' });
	return out.replace(/\n+$/, ''); // injectBetweenMarkers adds its own surrounding blank lines
}

// Full transform: given the current source texts, return the up-to-date PLUGINS.md text. Async
// because it defers markdown formatting to Prettier (see formatMarkdown).
/**
 * @param {string} typesSource
 * @param {string} pluginsMd
 * @param {string} wireSchemaJson
 * @returns {Promise<string>}
 */
export async function generatePluginsMd(typesSource, pluginsMd, wireSchemaJson) {
	const table = await formatMarkdown(renderInputTypeTable(parseInputTypes(typesSource)));
	let md = injectBetweenMarkers(pluginsMd, INPUT_TYPES_BEGIN, INPUT_TYPES_END, table);
	const wire = await formatMarkdown(renderWireTypes(wireSchemaJson));
	md = injectBetweenMarkers(md, WIRE_TYPES_BEGIN, WIRE_TYPES_END, wire);
	return md;
}

async function main() {
	const check = process.argv.includes('--check');
	const typesSource = readFileSync(TYPES_PATH, 'utf8');
	const current = readFileSync(PLUGINS_MD_PATH, 'utf8');
	const wireSchemaJson = readFileSync(WIRE_SCHEMA_PATH, 'utf8');
	const next = await generatePluginsMd(typesSource, current, wireSchemaJson);

	if (next === current) {
		console.log('generate-plugin-docs: PLUGINS.md is up to date.');
		return;
	}
	if (check) {
		console.error(
			'generate-plugin-docs: PLUGINS.md is STALE. Run `npm run generate-docs` and commit.'
		);
		process.exit(1);
	}
	writeFileSync(PLUGINS_MD_PATH, next);
	console.log('generate-plugin-docs: PLUGINS.md regenerated.');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	main().catch((err) => {
		console.error(err);
		process.exit(1);
	});
}
